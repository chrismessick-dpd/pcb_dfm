"""Stamp Fabcheck's version: a hash of the tool files, written to assets/version.js.

Run records carry this hash, so a re-run with a different Fabcheck build can say its findings may
differ. Run it after changing index.html or anything in assets/, before committing:

    python tools/stamp_version.py           # rewrite assets/version.js
    python tools/stamp_version.py --check   # exit 1 if it is stale
"""
import datetime
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
VERSION = ROOT / "assets" / "version.js"


def tool_files():
    files = [ROOT / "index.html"] + [p for p in (ROOT / "assets").rglob("*") if p.is_file() and p != VERSION]
    return sorted(files, key=lambda p: p.relative_to(ROOT).as_posix())


def tool_hash():
    h = hashlib.sha256()
    for p in tool_files():
        h.update(p.relative_to(ROOT).as_posix().encode())
        h.update(b"\0")
        h.update(p.read_bytes().replace(b"\r\n", b"\n"))
    return h.hexdigest()[:12]


def text(hash_):
    return ("/* Generated by tools/stamp_version.py - do not edit by hand. */\n"
            f"window.FABCHECK_VERSION = {{ \"hash\": \"{hash_}\" }};\n")


def main():
    want = text(tool_hash())
    have = VERSION.read_text(encoding="utf-8") if VERSION.exists() else ""
    if "--check" in sys.argv:
        if have != want:
            print("assets/version.js is stale: run python tools/stamp_version.py")
            sys.exit(1)
        print("version.js is current")
        return
    VERSION.write_text(want, encoding="utf-8", newline="\n")
    print("stamped", tool_hash(), datetime.date.today().isoformat())


if __name__ == "__main__":
    main()
